import { useState } from "react";
import {
  Sparkles,
  Play,
  RotateCw,
  Clock,
  Music2,
  Check
} from "lucide-react";
import { MOOD_CATEGORIES, GENRE_CATEGORIES, FALLBACK_AUDIO_TRACKS } from "../../data/mockData";
import { usePlayer } from "../../context/PlayerContext";

export const AIPlaylistGenerator = () => {
  const { playTrack, createPlaylist } = usePlayer();

  const [promptText, setPromptText] = useState("Cyberpunk late-night coding with warm ambient bass");
  const [selectedMood, setSelectedMood] = useState("focus");
  const [selectedGenre, setSelectedGenre] = useState("synthwave");
  const [durationMins, setDurationMins] = useState(30);
  const [isGenerating, setIsGenerating] = useState(false);
  const [generatedPlaylist, setGeneratedPlaylist] = useState(null);
  const [isSaved, setIsSaved] = useState(false);

  const durationOptions = [15, 30, 45, 60];

  const handleGenerate = (e) => {
    e.preventDefault();
    setIsGenerating(true);
    setIsSaved(false);

    setTimeout(() => {
      // Pick tracks that align with selected genre/mood
      const tracks = [...FALLBACK_AUDIO_TRACKS].sort(() => 0.5 - Math.random()).slice(0, 5);

      setGeneratedPlaylist({
        id: `ai-pl-${Date.now()}`,
        title: promptText ? `AI: ${promptText.slice(0, 32)}...` : "Neural Flow Session",
        prompt: promptText,
        mood: selectedMood,
        genre: selectedGenre,
        duration: `${durationMins} minutes`,
        songCount: tracks.length,
        tracks
      });
      setIsGenerating(false);
    }, 1600);
  };

  const handlePlayAll = () => {
    if (generatedPlaylist && generatedPlaylist.tracks.length > 0) {
      playTrack(generatedPlaylist.tracks[0], generatedPlaylist.tracks);
    }
  };

  const handleSaveToLibrary = () => {
    if (!generatedPlaylist) return;
    createPlaylist(generatedPlaylist.title, `Generated by AI Playlist Generator · ${generatedPlaylist.genre}`);
    setIsSaved(true);
  };

  return (
    <div className="ai-playlist-gen-page">
      <div className="generator-hero-header">
        <div className="generator-badge">
          <Sparkles size={14} className="text-pink-400" />
          <span>PROMPT-DRIVEN PLAYLIST ARCHITECT</span>
        </div>
        <h1 className="generator-title">AI Playlist Generator</h1>
        <p className="generator-subtitle">
          Describe the mood, environment, or story you want to feel, choose your parameters, and synthesize a complete curated album.
        </p>
      </div>

      {/* Generator Form */}
      <form className="generator-form-card" onSubmit={handleGenerate}>
        {/* Prompt Input */}
        <div className="form-group">
          <label className="form-label">
            Describe your desired vibe or scenario:
          </label>
          <textarea
            className="generator-textarea"
            rows="3"
            value={promptText}
            onChange={(e) => setPromptText(e.target.value)}
            placeholder="e.g. Rainy midnight drive through neo-Tokyo highways with mellow electronic beats..."
          />
        </div>

        {/* Mood Selection */}
        <div className="form-group">
          <label className="form-label">Select Mood:</label>
          <div className="mood-pills-row">
            {MOOD_CATEGORIES.map((m) => (
              <button
                type="button"
                key={m.id}
                className={`mood-pill-btn ${selectedMood === m.id ? "active" : ""}`}
                onClick={() => setSelectedMood(m.id)}
              >
                {m.name}
              </button>
            ))}
          </div>
        </div>

        {/* Genre & Duration Grid */}
        <div className="form-split-grid">
          <div className="form-group">
            <label className="form-label">Preferred Music Genre:</label>
            <select
              className="generator-select"
              value={selectedGenre}
              onChange={(e) => setSelectedGenre(e.target.value)}
            >
              {GENRE_CATEGORIES.map((g) => (
                <option key={g.id} value={g.id}>
                  {g.name}
                </option>
              ))}
            </select>
          </div>

          <div className="form-group">
            <label className="form-label">Target Duration:</label>
            <div className="duration-options">
              {durationOptions.map((mins) => (
                <button
                  type="button"
                  key={mins}
                  className={`duration-btn ${durationMins === mins ? "active" : ""}`}
                  onClick={() => setDurationMins(mins)}
                >
                  <Clock size={14} />
                  <span>{mins}m</span>
                </button>
              ))}
            </div>
          </div>
        </div>

        {/* Submit Button */}
        <button
          type="submit"
          className={`generate-submit-btn ${isGenerating ? "loading" : ""}`}
          disabled={isGenerating}
        >
          {isGenerating ? (
            <>
              <RotateCw size={18} className="animate-spin" />
              <span>Synthesizing Custom Playlist...</span>
            </>
          ) : (
            <>
              <Sparkles size={18} />
              <span>Generate Playlist</span>
            </>
          )}
        </button>
      </form>

      {/* Generated Results Preview */}
      {generatedPlaylist && (
        <div className="generated-playlist-result">
          <div className="result-header">
            <div className="result-info">
              <span className="result-pill">AI GENERATED PLAYLIST</span>
              <h2>{generatedPlaylist.title}</h2>
              <p className="result-meta">
                {generatedPlaylist.songCount} tracks · {generatedPlaylist.duration} · {generatedPlaylist.mood.toUpperCase()} · {generatedPlaylist.genre.toUpperCase()}
              </p>
            </div>

            <div className="result-actions">
              <button className="result-play-btn" onClick={handlePlayAll}>
                <Play size={18} className="fill-current text-white translate-x-0.5" />
                <span>Play All</span>
              </button>

              <button
                className={`result-save-btn ${isSaved ? "saved" : ""}`}
                onClick={handleSaveToLibrary}
              >
                {isSaved ? <Check size={16} /> : <Music2 size={16} />}
                <span>{isSaved ? "Saved to Library" : "Save to Library"}</span>
              </button>
            </div>
          </div>

          <div className="result-tracks-grid">
            {generatedPlaylist.tracks.map((track) => (
              <div
                key={track.id}
                className="result-track-card"
                onClick={() => playTrack(track, generatedPlaylist.tracks)}
              >
                <div className="track-art-box">
                  <img src={track.image} alt={track.title} />
                  <button className="play-hover-btn">
                    <Play size={16} className="fill-current" />
                  </button>
                </div>
                <div className="track-desc">
                  <h4>{track.title}</h4>
                  <p>{track.artist}</p>
                </div>
              </div>
            ))}
          </div>
        </div>
      )}
    </div>
  );
};
